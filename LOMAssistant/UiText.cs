	private class Lang
	{
		public readonly Dictionary<string, string> Exact = new Dictionary<string, string>();
		public readonly List<(Regex, string)> Patterns = new List<(Regex, string)>();
		public readonly List<(Regex, MatchEvaluator)> Names = new List<(Regex, MatchEvaluator)>();
		public readonly List<(Regex, MatchEvaluator)> Words = new List<(Regex, MatchEvaluator)>();
		public readonly Dictionary<string, string> Cache = new Dictionary<string, string>();
		// 英语：英文补丁（velvetcakes）的翻译文件，查来自游戏的文字；本 Mod 自己的表优先
		public readonly Dictionary<string, string> Game;

		public Lang(int column)
		{
			Game = column == 3 ? XUnityTranslations.Load() : new Dictionary<string, string>();
			string[][] conditions = NameColumn(UiConditionNames.Table, column);
			if (conditions.Length > 0)
			{
				Names.Add(ConditionNames(conditions));
			}
			string[][] flags = NameColumn(UiFlagNames.Table, column);
			if (flags.Length > 0)
			{
				Names.Add(FlagNames(flags));
			}
			Words.Add(ChineseNumeralDates);
			foreach (var (pattern, korean, japanese, english) in ActionWords)
			{
				string text = column == 1 ? korean : column == 2 ? japanese : english;
				if (text != null)
				{
					Words.Add((new Regex(pattern), _ => text));
				}
			}
			Words.AddRange(column == 1 ? KoreanDates : column == 2 ? JapaneseDates : EnglishDates);
			foreach (string[] row in (column == 3 ? UiTextEnglish.Terms.Keys.Select(k => new[] { k }) : Terms).OrderByDescending(r => r[0].Length))
			{
				string text = Column(row, column, UiTextEnglish.Terms);
				if (text == null)
				{
					continue;
				}
				// 换行、富文本拆段后，连接词可能位于段首；复用原词条，避免漏掉「且」「或」。
				if (row[0] == " 且 " || row[0] == "\n或 ")
				{
					Words.Add((new Regex("^" + Regex.Escape(row[0].TrimStart())), _ => text.TrimStart()));
				}
				Words.Add((new Regex(Regex.Escape(row[0])), _ => text));
			}
			// 任务名：窗口里常截短成「前 N 个字…」显示，截短后的也认得，换成同样截短的译文
			// 没有当前语言译文的跳过，仍可由游戏翻译或原文回退。
			foreach (string[] row in UiQuestNames.Table)
			{
				string zh = row[0], text = Column(row, column);
				if (text == null)
				{
					continue;
				}
				Exact[zh] = text;
				foreach (int n in ShortLengths)
				{
					if (zh.Length > n)
					{
						Exact[zh.Substring(0, n) + "…"] = text.Length > n + 2 ? text.Substring(0, n + 2) + "…" : text;
					}
				}
			}
			foreach (string[] row in (column == 3 ? UiTextEnglish.Table.Keys.Select(k => new[] { k }) : Table).OrderByDescending(r => r[0].Length))
			{
				string zh = row[0], text = Column(row, column, UiTextEnglish.Table);
				if (text == null)
				{
					continue;
				}
				if (zh.Contains("{0}"))
				{
					string regex = "^" + Regex.Replace(Regex.Escape(zh), @"\\\{(\d)}", "(.+?)") + "$";
					Patterns.Add((new Regex(regex), text));
				}
				else
				{
					Exact[zh] = text;
				}
			}
		}
	}

	// 名称表的列：0 是原文，1 韩语、2 日语、3 英语；中文界面仍走原来的简繁转换。
	internal static int LanguageColumn(string language) => language == Korean ? 1 : language == Japanese ? 2 : language == English ? 3 : 0;

	// 缺列和 null 都表示未翻译，不借用其他语言的译文。
	internal static string Column(string[] row, int column) => column > 0 && column < row.Length ? row[column] : null;

	// 只查通用界面表里的原始译文，不做句式匹配，也不初始化语言词典；未翻译时返回 null。
	internal static string TableTranslation(string key, string language)
	{
		if (language == English)
		{
			return UiTextEnglish.Table.TryGetValue(key, out string text) ? text : null;
		}
		string[] row = Table.LastOrDefault(item => item[0] == key);
		return row != null ? Column(row, LanguageColumn(language)) : null;
	}

	private static string[][] NameColumn(string[][] table, int column) => table.Where(row => Column(row, column) != null).Select(row => new[] { row[0], row[column] }).ToArray();

	// 通用界面表的英语仍从 UiTextEnglish 按中文查，保留现有词典和优先级。
	private static string Column(string[] row, int column, Dictionary<string, string> english)
	{
		return column < 3 ? Column(row, column) : english.TryGetValue(row[0], out string text) ? text : null;
	}

