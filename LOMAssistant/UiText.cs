	public const string Korean = "Korean";
	public const string Japanese = "Japanese";
	public const string English = "English";

	/// <summary>换成指定界面语言；查不到的部分原样。</summary>
	public static string Translate(string text, string language)
	{
		if (string.IsNullOrEmpty(text))
		{
			return text;
		}
		Lang lang = language == Korean ? KoreanLang : language == Japanese ? JapaneseLang : language == English ? EnglishLang : null;
		if (lang == null)
		{
			return text;
		}
		if (lang.Cache.TryGetValue(text, out string done))
		{
			return done;
		}
		if (lang.Cache.Count >= 20000)
		{
			lang.Cache.Clear();
		}
		string result = text.IndexOf('<') >= 0
			? string.Concat(Tags.Split(text).Select(part => Tag.IsMatch(part) ? part : Segment(part, lang)))
			: Segment(text, lang);
		lang.Cache[text] = result;
		return result;
	}

	// 只认 Unity 富文本的标签。条件里的「需<=40 且 … 需>=2」也有「<」「>」，以前当成一个标签整段不翻
	private const string TagPattern = @"</?(?:b|i|size|color|material|quad)(?:[= ][^<>]*)?>";
	private static readonly Regex Tags = new Regex("(" + TagPattern + ")");
	private static readonly Regex Tag = new Regex("^" + TagPattern + "$");
	private static readonly Regex Sections = new Regex(@"(\n| · |　·　|　+| → )");
	private static readonly Regex Separators = new Regex(@"( {2,}|・|、)");
	private static readonly Regex Han = new Regex(@"[一-鿿]");
	private static readonly char[] Blank = { ' ', '　', '\n', '\r', '\t' };

	private static string Segment(string text, Lang lang, int depth = 0)
	{
		string found = Whole(text, lang, depth);
		if (found != null)
		{
			return found;
		}
		// 先分开外层段落，保留「（要 …）」等句式内部的空格；名称也可能带顿号，要先完整识别。
		string[] parts = Sections.Split(text);
		if (parts.Length <= 1)
		{
			foreach (var (pattern, replace) in lang.Names)
			{
				text = pattern.Replace(text, replace);
			}
			parts = Separators.Split(text);
		}
		if (parts.Length <= 1)
		{
			return Words(text, lang);
		}
		return string.Concat(parts.Select(part => depth < 8 && part.Length < text.Length ? Segment(part, lang, depth + 1) : Words(part, lang)));
	}

	// 最后一步：只换日期和常见的界面词
	private static string Words(string text, Lang lang)
	{
		if (!Han.IsMatch(text))
		{
			return text;
		}
		foreach (var (pattern, replace) in lang.Names.Concat(lang.Words))
		{
			text = pattern.Replace(text, replace);
		}
		return text;
	}

	// 整段（去掉首尾空白后）查表、查句式；查不到返回 null
	private static string Whole(string text, Lang lang, int depth = 0)
	{
		string core = text.Trim(Blank);
		if (core.Length == 0)
		{
			return null;
		}
		string found = null;
		if (!lang.Exact.TryGetValue(core, out found))
		{
			foreach (var (pattern, format) in lang.Patterns)
			{
				Match m = pattern.Match(core);
				if (m.Success)
				{
					// 参数也可能是由句式或名称拼成的列表，复用分段翻译；只递归更短的原文，最多再查八层。
					found = string.Format(format, m.Groups.Cast<Group>().Skip(1).Select(g => (object)(
						lang.Exact.TryGetValue(g.Value, out string part) || lang.Game.TryGetValue(g.Value, out part)
							? part
							: depth < 8 && g.Length < core.Length ? Segment(g.Value, lang, depth + 1) : Words(g.Value, lang))).ToArray());
					break;
				}
			}
		}
		if (found == null && !lang.Game.TryGetValue(core, out found))
		{
			return null;
		}
		int start = text.IndexOf(core, System.StringComparison.Ordinal);
		return text.Substring(0, start) + found + text.Substring(start + core.Length);
	}

	// 旗标名：常拼在条件、提示里（「名字 (编号) 需=1」「【旗标】名字  0 → 1」），比日期、界面词先换，免得名字里的字先被换掉。
	// 三个字以内的（「天道」「投票」「古文」这类）容易撞上别的文字，只在后面紧跟「 (编号)」、「=值」「 值」（选项结果里的
	// 「设置名字=1」）、两个空格或整段结尾时换。备注末尾常带着 \r、\t、空格（「抢劫\t (M20013)」），中间隔着空白也算
	private static (Regex, MatchEvaluator) FlagNames(string[][] table)
	{
		// 备注换行压成一行后可能留下回车或连续空格；只在名称匹配中兼容，不改其他界面文字。
		string Key(string name) => Regex.Replace(name, @"[ \t\r]+", " ");
		var map = new Dictionary<string, string>();
		foreach (string[] row in table)
		{
			map[Key(row[0])] = row[1];
		}
		string Alternatives(IEnumerable<string> names) => string.Join("|", names.OrderByDescending(n => n.Length)
			.Select(n => Regex.Escape(n).Replace(@"\ ", @"[ \t\r]+")).ToArray());
		var patterns = new List<string>();
		if (map.Keys.Any(n => n.Length > 3))
		{
			patterns.Add("(?:" + Alternatives(map.Keys.Where(n => n.Length > 3)) + ")");
		}
		if (map.Keys.Any(n => n.Length <= 3))
		{
			patterns.Add("(?:" + Alternatives(map.Keys.Where(n => n.Length <= 3)) + ")(?=\\s*\\(|\\s*=|\\s+[+-]?\\d|\\s{2}|\\s*$)");
		}
		var regex = new Regex(string.Join("|", patterns));
		return (regex, m => map[Key(m.Value)]);
	}

	// 条件里的变量名（「嘴力 需>=40」「目前时间 需<=…」「好感度_三师兄 需>好感度_二师兄」）：只在条件格式里换，
	// 名字后面跟「 需」或比较符，或跟在比较符后面（流程图会省略「需」）。要比旗标名先换：「攻略小师妹 (攻略人數)」「天道 (六道總點數)」
	// 这类名字里的「攻略小师妹」「天道」也是旗标名，先被换掉就对不上了
	private static (Regex, MatchEvaluator) ConditionNames(string[][] table)
	{
		var map = new Dictionary<string, string>();
		foreach (string[] row in table)
		{
			map[row[0]] = row[1];
		}
		// 剧情条件会转成简体；复用原词条，显式键优先于转换得到的别名。
		foreach (string[] row in table)
		{
			string simplified = TextConverter.ToSimplified(row[0]);
			if (!map.ContainsKey(simplified))
			{
				map[simplified] = row[1];
			}
		}
		string names = string.Join("|", map.Keys.OrderByDescending(n => n.Length).Select(Regex.Escape).ToArray());
		const string comparison = "(?:>=|<=|!=|=|>|<|≥|≤|≠)";
		// 完整「否则」说明用分号分开条件，也要先识别整名，再翻其中的物品名。
		var regex = new Regex("(?<=" + comparison + ")(?:" + names + ")(?=$|\\s|<|；)|(?<=^|\\s|；)(?:" + names + ")(?= 需|\\s*" + comparison + ")");
		return (regex, m => map[m.Value]);
	}

	// 条件里的日期是中文数字（「第三年一月上旬」）：先换成「第3年1月上旬」，再按各语言的日期规则转换
	private static readonly (Regex, MatchEvaluator) ChineseNumeralDates = (new Regex("第([一二三四五六七八九十]+)年([一二三四五六七八九十]+)月"),
		m => "第" + ChineseNumber(m.Groups[1].Value) + "年" + ChineseNumber(m.Groups[2].Value) + "月");

	// 一～九十九的中文数字（「十」「十二」「二十」）
	private static int ChineseNumber(string text)
	{
		const string digits = "一二三四五六七八九";
		int ten = text.IndexOf('十');
		if (ten < 0)
		{
			return digits.IndexOf(text[0]) + 1;
		}
		int tens = ten == 0 ? 1 : digits.IndexOf(text[0]) + 1;
		int ones = ten == text.Length - 1 ? 0 : digits.IndexOf(text[ten + 1]) + 1;
		return tens * 10 + ones;
	}

	// 选项结果（LuaParser）拼出来的动作说明里的词：「设置X=1」「X好感 +3」「天赋X lv1」「丢弃X」「X向心力 +1」「后续: …」「对决」「混战」，
	// 和条件里的当前值「→ 当前1」（按「 → 」切开后单独剩下「当前1」，表里的「→ 当前」对不上）。
	// 只在这种格式里换（「设置页」不换）。对应语言为 null 的照旧显示中文
