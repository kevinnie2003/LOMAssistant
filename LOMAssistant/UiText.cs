/// <summary>
/// 界面文字的韩语、日语、英语（通用界面的英语译文在 UiTextEnglish，名称见各名称表）。本 Mod 的文字都是用简体写的，显示前按这张表换：
/// 先整句查；查不到再查带 {0} 的句式（拼进去的数字、按键、名字原样保留）；
/// 带颜色等标签的、用「 · 」「　」或换行拼起来的，拆开一段段查。查不到的照原样显示中文。
/// 表里的译文欢迎懂韩语、日语的玩家指正。
/// </summary>
public static class UiText
